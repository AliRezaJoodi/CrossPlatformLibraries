#define NTC100K_TABLE_SIZE (sizeof(NTC100K_Table5C) / sizeof(NTC100K_Table5C[0]))

int16_t NTC100K_ConvertOhmToTemp(uint32_t R){
    uint8_t i;
    uint32_t R1, R2;
    int16_t t;

    if(R >= NTC100K_Table5C[0]){
        return 0;
    }

    if(R <= NTC100K_Table5C[NTC100K_TABLE_SIZE-1]){
        return (NTC100K_TABLE_SIZE-1) * 5;
    }

    for(i = 0; i < (NTC100K_TABLE_SIZE - 1); i++){
        R1 = NTC100K_Table5C[i];
        R2 = NTC100K_Table5C[i+1];

        if(R <= R1 && R >= R2){
            t = i * 5;
            t += (5 * (R1 - R)) / (R1 - R2);
            return t;
        }
    }

    return -1000;
}

