#define NTC10K_TABLE_SIZE (sizeof(ntc10k_table) / sizeof(ntc10k_table[0]))

//********************************************
int16_t NTC10K_ConvertOhmToTemp(uint32_t ohm){
    if(ohm >= ntc10k_table[0]){
        return -25;
    }

    if(ohm <= ntc10k_table[NTC10K_TABLE_SIZE - 1]){
        return 125;
    }

    return 0;
}