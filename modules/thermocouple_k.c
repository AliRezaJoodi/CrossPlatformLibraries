#define TC_K_TABLE_SIZE (sizeof(TC_K_Table10C) / sizeof(TC_K_Table10C[0]))

//******************************************
int16_t TC_ConvertMicroVoltToTemp(int32_t uv){
    int16_t i = 0;
    int32_t uv0 = 0;
    int32_t uv1 = 0;
    int32_t t0 = 0;
    int32_t result = 0;

    if(uv <= TC_K_Table10C[0]){
        return TC_K_TEMP_MIN;
    }

    if(uv >= TC_K_Table10C[TC_K_TABLE_SIZE-1]){
        return TC_K_TEMP_MAX;
    }

    for(i = 0; i < (TC_K_TABLE_SIZE-1); i++){
        if(uv < TC_K_Table10C[i+1]){
            uv0 = TC_K_Table10C[i];
            uv1 = TC_K_Table10C[i+1];

            t0 = TC_K_TEMP_MIN + ((int32_t)i * 10);

            result = (t0 + (((uv - uv0) * 10) / (uv1 - uv0)));
            return (int16_t)result;
        }
    }

    return TC_K_ERROR;
}

//******************************************
int32_t TC_ConvertTempToMicroVolt(int16_t temp){
    int16_t index = 0;
    int16_t t0 = 0;
    int16_t dt = 0;
    int32_t uv0 = 0;
    int32_t uv1 = 0;
    int32_t duv = 0;
    int32_t result = 0;

    // Clamp temperature to table limits (-270°C to +1370°C)
    if (temp <= -270){
        return TC_K_Table10C[0];
    }

    if (temp >= 1370){
        return TC_K_Table10C[TC_K_TABLE_SIZE - 1];
    }

    // Compute table index (each entry represents 10°C)
    index = (temp + 270) / 10;

    // Base temperature for this table cell
    t0 = (index * 10) - 270;

    // Lookup microvolt values
    uv0 = TC_K_Table10C[index];       // µV at t0
    uv1 = TC_K_Table10C[index + 1];   // µV at t0 + 10°C

    // If temperature exactly matches a 10°C grid point
    if (temp == t0){
        return uv0;
    }

    // Linear interpolation (integer math, no floats)
    dt  = temp - t0;   // offset from base temperature (0..10)
    duv = uv1 - uv0;   // delta µV between table entries

    // Return interpolated microvolt value
    result = uv0 + ((duv * dt) / 10);
    return result;
}


